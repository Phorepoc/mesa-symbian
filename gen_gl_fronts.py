"""gen_gl_fronts -- the frozen-ABI Khronos DLL fronts over the Mesa backend DLL: libEGL/libGLESv2/libGLESv1_CM are
thin thunks bound at load to the backend (phgl.dll), so their 2010 ordinals stay fixed whatever Mesa exports.

Reads the 2010 frozen .defs (the ordinals every Symbian GL app links against) and the public 2010 headers (the
prototypes), and writes into core's os/src/phgl/gen/:
  phgl.def             the backend's exports: Mesa's EGL + GLES2 + GLES1 entry points at OUR ordinals
                       (EGL: the libegl14U ordinal; GLES2: 100 + libglesv2u's; GLES1-only: 400 + libglesv1_cm11u's)
  libegl_front.cpp     libEGL.dll     (libegl14U.def, 34 functions)
  libglesv2_front.cpp  libGLESv2.dll  (libglesv2u.def, 142)
  libglesv1_front.cpp  libGLESv1_CM.dll (libglesv1_cm11u.def, 157)
Each front function looks its target up ONCE in phgl.dll (RLibrary::Lookup by ordinal; a name phgl does not
export -- the GLES1 OES extensions Mesa only reaches through eglGetProcAddress -- is resolved by that instead),
then tail-calls it. A front never links phgl.lib: its own export names would clash with the imports.

    python3 gen_gl_fronts.py          (after build_mesa_symbian.py; PHOREPOC_CORE, PHOREPOC_SYMBIAN, PHOREPOC_BUILD)
"""
from __future__ import annotations

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
CORE = os.path.abspath(os.environ.get("PHOREPOC_CORE") or os.path.join(HERE, "..", "core"))
SYMBIAN = os.path.abspath(os.environ.get("PHOREPOC_SYMBIAN") or os.path.join(CORE, "symbian"))
BUILD = os.path.abspath(os.environ.get("PHOREPOC_BUILD") or os.path.join(CORE, "build"))
B = os.path.join(SYMBIAN, "symbian-2010")
G = os.path.join(B, "oss.FCL.sf.os.graphics")
INC = os.path.join(B, "oss.API_REF.Public_API", "epoc32", "include")
OUT = os.path.join(CORE, "os", "src", "phgl", "gen")
GEN = os.path.join(BUILD, "mesa-build", "gen")

DEFS = {
    "egl": os.path.join(G, "egl/eglinterface/eabi/libegl14U.def"),
    "gles2": os.path.join(G, "opengles/openglesinterface/eabi/libglesv2u.def"),
    "gles1": os.path.join(G, "opengles/openglesinterface/eabi/libglesv1_cm11u.def"),
    # libGLES_CM.dll: the older S60 name of GLES 1.x, its own frozen table, which ALSO exports the egl* functions
    # (S^3 ROMs carry both; SDK games link it -- King Oddball, 2026-10-12)
    "gles_cm": os.path.join(G, "opengles/openglesinterface/eabi/opengles11u.def"),
}
HEADERS = {
    "egl": [os.path.join(INC, "EGL/egl.h")],
    "gles2": [os.path.join(INC, "GLES2/gl2.h")],
    "gles1": [os.path.join(INC, "GLES/gl.h"), os.path.join(INC, "GLES/glext.h")],
}
ORD_BASE = {"egl": 0, "gles2": 100, "gles1": 400}


def read_def(path: str) -> list[tuple[int, str]]:
    out = []
    for line in open(path, encoding="latin-1"):
        m = re.match(r"\s*(\w+)\s*@\s*(\d+)\s*NONAME(.*)", line)
        if m and "ABSENT" not in m.group(3):
            out.append((int(m.group(2)), m.group(1)))
    return out


PROTO = re.compile(r"(?:EGLAPI|GL_APICALL|GL_API)\s+([^;#\n]*?)\s*(?:EGLAPIENTRY|GL_APIENTRY)\s*(\w+)\s*\(([^;#]*?)\)\s*(__SOFTFP)?\s*;",
                   re.S)


def read_protos(paths: list[str]) -> dict[str, tuple[str, str, bool]]:
    """name -> (return type, argument list text, softfp)"""
    out = {}
    for p in paths:
        text = open(p, encoding="latin-1").read()
        text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
        text = re.sub(r"^\s*#.*$", "", text, flags=re.M)      # preprocessor lines (a #define can mention EGLAPI)
        for m in PROTO.finditer(text):
            ret, name, args, softfp = m.group(1), m.group(2), m.group(3), bool(m.group(4))
            args = " ".join(args.split())
            out.setdefault(name, (" ".join(ret.split()), args, softfp))
    return out


def arg_names(args: str) -> list[str]:
    if args.strip() in ("", "void"):
        return []
    names = []
    for a in args.split(","):
        a = a.strip().rstrip("]").split("[")[0]
        names.append(re.findall(r"\w+", a)[-1])
    return names


def arg_types(args: str) -> str:
    """the parameter list without names (for the function-pointer typedef)"""
    if args.strip() in ("", "void"):
        return "void"
    out = []
    for a in args.split(","):
        a = a.strip()
        m = re.match(r"(.*?)(\w+)\s*(\[.*\])?$", a)
        t = (m.group(1) + (m.group(3) or "")).strip() if m else a
        out.append(t)
    return ", ".join(out)


def mesa_names(header: str) -> set[str]:
    names = set()
    if os.path.isfile(header):
        for m in re.finditer(r"GLAPIENTRY\s+(gl\w+)\s*\(", open(header, encoding="latin-1").read()):
            names.add(m.group(1))
    return names


FRONT_HEAD = """// {out} -- GENERATED by mesa-symbian/gen_gl_fronts.py from {deffile} -- do not edit.
// {dll}: the frozen Symbian ABI front over phgl.dll (Mesa). Every function resolves its backend entry once (ordinal
// lookup in phgl.dll, else phgl's eglGetProcAddress) and calls it; without phgl.dll it returns 0 / does nothing.
#include <e32std.h>
#include <e32debug.h>
{includes}
#include "../phgl_front.h"

namespace
\t{{
\tTLibraryFunction gFn[{n}];
\tinline TLibraryFunction Fn(TInt aIdx, TInt aOrdinal, const char* aName)
\t\t{{
\t\treturn gFn[aIdx] ? gFn[aIdx] : (gFn[aIdx] = PhglResolve(aOrdinal, aName));
\t\t}}
\t// egl* of a front that re-exports them (libGLES_CM): libEGL.dll's function at its libegl14U ordinal
\tinline TLibraryFunction EglFn(TInt aIdx, TInt aOrdinal, const char* aName)
\t\t{{
\t\treturn gFn[aIdx] ? gFn[aIdx] : (gFn[aIdx] = PhglResolveEgl(aOrdinal, aName));
\t\t}}
\t}}

extern "C"
{{
"""


def gen_front(api: str, dll: str, protos: dict, ordinals: dict[str, int], out_name: str, includes: list[str],
              egl_ordinals: dict[str, int] | None = None) -> None:
    """egl_ordinals: this front also exports egl* (libGLES_CM) -- those go to libEGL.dll (the dispatcher that owns the
    display; never phgl directly), looked up there by their libegl14U ordinal (PhglResolveEgl)."""
    entries = read_def(DEFS[api])
    lines = [FRONT_HEAD.format(out=out_name, deffile=os.path.basename(DEFS[api]), dll=dll,
                               includes="\n".join(f"#include <{i}>" for i in includes), n=len(entries))]
    missing = []
    for idx, (_, name) in enumerate(entries):
        ord_ = ordinals.get(name, 0)
        fn = "Fn"
        if egl_ordinals is not None and name.startswith("egl"):
            ord_, fn = egl_ordinals[name], "EglFn"
        if name == "eglGetProcAddress":
            lines.append(f"void (*eglGetProcAddress(const char* procname))(...)\n\t{{\n"
                         f"\ttypedef void (*(*F)(const char*))(...);\n"
                         f"\tF f = (F){fn}({idx}, {ord_}, \"{name}\");\n"
                         f"\treturn f ? f(procname) : 0;\n\t}}\n")
            continue
        if name not in protos:
            missing.append(name)
            continue
        ret, args, softfp = protos[name]
        names = arg_names(args)
        types = arg_types(args)
        attr = " __SOFTFP" if softfp else ""
        call = f"f({', '.join(names)})"
        body = f"return {call};" if ret != "void" else f"{call};"
        fail = f"return ({ret})0;" if ret != "void" else "return;"
        # TRACE (landscape black band, 2026-10-12): the first calls of the size-carrying functions, as "PH:" lines the
        # kernel seam forwards to PhoneLab -- bounded (16 each), so a game's per-frame viewport cannot flood the link
        trace = ""
        if name in ("glViewport", "glScissor"):
            trace = (f"\tstatic TInt traced;\n\tif (traced < 16)\n\t\t{{ ++traced; "
                     f"RDebug::Printf(\"PH: {dll} {name}(%d,%d,%d,%d)\", (TInt)x, (TInt)y, (TInt)width, (TInt)height); }}\n")
        if name == "eglQuerySurface":
            body = (f"EGLBoolean r = {call};\n\tstatic TInt traced;\n\tif (traced < 16 && value)\n"
                    f"\t\t{{ ++traced; RDebug::Printf(\"PH: {dll} eglQuerySurface(0x%x) -> %d (r=%d)\", (TInt)attribute, "
                    f"(TInt)*value, (TInt)r); }}\n\treturn r;")
        lines.append(f"{ret} {name}({args}){attr}\n\t{{\n"
                     f"{trace}"
                     f"\ttypedef {ret} (*F)({types}){attr};\n"
                     f"\tF f = (F){fn}({idx}, {ord_}, \"{name}\");\n"
                     f"\tif (!f)\n\t\t{fail}\n"
                     f"\t{body}\n\t}}\n")
    lines.append("}\n")
    if missing:
        raise SystemExit(f"{api}: no prototype for {missing}")
    with open(os.path.join(OUT, out_name), "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"  {out_name}: {len(entries)} functions")


def main() -> None:
    os.makedirs(OUT, exist_ok=True)
    protos = {api: read_protos(HEADERS[api]) for api in HEADERS}
    es2 = mesa_names(os.path.join(GEN, "es2_glapi_mapi_tmp.h"))
    es1 = mesa_names(os.path.join(GEN, "es1_glapi_mapi_tmp.h"))
    if not es2 or not es1:
        raise SystemExit("run build_mesa_symbian.py first (<build>/mesa-build/gen/*_glapi_mapi_tmp.h)")

    # phgl.def: what the backend exports, at our ordinals
    ordinals: dict[str, int] = {}
    exports: list[tuple[int, str]] = []
    for ord_, name in read_def(DEFS["egl"]):
        ordinals[name] = ORD_BASE["egl"] + ord_
        exports.append((ordinals[name], name))
    for ord_, name in read_def(DEFS["gles2"]):
        if name in es2:
            ordinals[name] = ORD_BASE["gles2"] + ord_
            exports.append((ordinals[name], name))
    for ord_, name in read_def(DEFS["gles1"]):
        if name in ordinals:
            continue                       # shared with GLES2: one entry point serves both (glapi dispatch)
        if name in es1 or name in es2:
            ordinals[name] = ORD_BASE["gles1"] + ord_
            exports.append((ordinals[name], name))
    exports.sort()
    with open(os.path.join(OUT, "phgl.def"), "w", newline="\n") as f:
        f.write("EXPORTS\n")
        for ord_, name in exports:
            f.write(f"\t{name} @ {ord_} NONAME\n")
    print(f"  phgl.def: {len(exports)} exports")
    unresolved = [n for _, n in read_def(DEFS["gles1"]) if n not in ordinals]
    print(f"  GLES1 names phgl does not export (eglGetProcAddress at first call): {' '.join(unresolved)}")

    # (libEGL.dll is hand-written -- src/phgl/libegl_front.cpp, a dispatcher: the display and the reusable syncs the
    # window server needs stay out of phgl.dll; its EGL ordinals are phgl.def's = libegl14U.def's)
    gen_front("gles2", "libGLESv2.dll", protos["gles2"], ordinals, "libglesv2_front.cpp", ["GLES2/gl2.h"])
    gen_front("gles1", "libGLESv1_CM.dll", protos["gles1"], ordinals, "libglesv1_front.cpp",
              ["GLES/gl.h", "GLES/glext.h"])
    gen_front("gles_cm", "libGLES_CM.dll", {**protos["gles1"], **protos["egl"]}, ordinals, "libgles_cm_front.cpp",
              ["GLES/gl.h", "GLES/glext.h", "EGL/egl.h"], egl_ordinals=dict((n, o) for o, n in read_def(DEFS["egl"])))


if __name__ == "__main__":
    main()
